# Builds the self-hosted Poppins in public/fonts and the copies next/og uses.
# Poppins has no arrows, so Inter's are merged in: on Windows a glyph missing
# from the page font costs a fresh visit up to a second of font fallback search
#
#   pip install fonttools brotli
#   python scripts/fonts.py
#
# then commit public/fonts, app/fonts.css, lib/fonts.ts and lib/og/fonts
import hashlib
import io
import pathlib
import urllib.request

from fontTools import subset
from fontTools.merge import Merger
from fontTools.ttLib import TTFont
from fontTools.ttLib.scaleUpem import scale_upem
from fontTools.varLib.instancer import instantiateVariableFont

# google/fonts at a fixed commit, so a rebuild gives the same files
SOURCE = "https://raw.githubusercontent.com/google/fonts/e7db6ca603fd4862010383ff17ffd6cc4ffac1c0/ofl"
WEIGHTS = {400: "Regular", 500: "Medium", 600: "SemiBold"}
# the og images only need these two
OG_WEIGHTS = (400, 600)

WEB = pathlib.Path(__file__).resolve().parent.parent

# Google's latin subset plus Latin Extended-A (names like Łukasz or Søren) and
# the math signs Poppins draws
POPPINS_TEXT = (
    "U+0000-00FF,U+0100-017F,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,"
    "U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2212,U+2215,"
    "U+2248,U+2260,U+2264-2265,U+FEFF,U+FFFD"
)
# taken from Inter: every arrow it has, check marks and stars
INTER_SYMBOLS = "U+2190-21FF,U+2713,U+2717,U+2605-2606"


def unicodes(ranges: str) -> list[int]:
    out = []
    for part in ranges.split(","):
        lo, _, hi = part.removeprefix("U+").partition("-")
        out.extend(range(int(lo, 16), int(hi or lo, 16) + 1))
    return out


def fetch(path: str) -> TTFont:
    with urllib.request.urlopen(f"{SOURCE}/{path}") as response:
        return TTFont(io.BytesIO(response.read()))


def cut(font: TTFont, codepoints: list[int], keep_layout: bool) -> TTFont:
    options = subset.Options()
    options.hinting = False
    options.desubroutinize = True
    options.name_IDs = ["*"]
    options.notdef_outline = True
    if not keep_layout:
        options.layout_features = []
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    return font


def save(font: TTFont, flavor: str | None) -> bytes:
    buffer = io.BytesIO()
    font.flavor = flavor
    font.save(buffer)
    return buffer.getvalue()


def build(weight: int, inter: bytes) -> TTFont:
    poppins = cut(fetch(f"poppins/Poppins-{WEIGHTS[weight]}.ttf"), unicodes(POPPINS_TEXT), True)
    have = set(poppins.getBestCmap())

    symbols = TTFont(io.BytesIO(inter))
    instantiateVariableFont(symbols, {"wght": weight, "opsz": 14}, inplace=True)
    missing = [c for c in unicodes(INTER_SYMBOLS) if c not in have]
    cut(symbols, missing, False)
    scale_upem(symbols, poppins["head"].unitsPerEm)
    for font in (poppins, symbols):
        for table in ("fpgm", "prep", "cvt ", "gasp", "hdmx", "LTSH", "VDMX", "DSIG"):
            if table in font:
                del font[table]

    with io.BytesIO() as a, io.BytesIO() as b:
        poppins.save(a)
        symbols.save(b)
        a.seek(0)
        b.seek(0)
        # the first font's name, metrics and features win
        return Merger().merge([a, b])


def main():
    with urllib.request.urlopen(f"{SOURCE}/inter/Inter%5Bopsz%2Cwght%5D.ttf") as response:
        inter = response.read()

    public = WEB / "public" / "fonts"
    og = WEB / "lib" / "og" / "fonts"
    public.mkdir(parents=True, exist_ok=True)
    og.mkdir(parents=True, exist_ok=True)
    for old in public.glob("poppins-*.woff2"):
        old.unlink()

    files = {}
    for weight in WEIGHTS:
        font = build(weight, inter)
        woff2 = save(font, "woff2")
        name = f"poppins-{weight}.{hashlib.sha256(woff2).hexdigest()[:10]}.woff2"
        (public / name).write_bytes(woff2)
        files[weight] = name
        if weight in OG_WEIGHTS:
            (og / f"poppins-{weight}.ttf").write_bytes(save(font, None))
        print(f"{name}: {len(woff2)} bytes, {len(font.getBestCmap())} characters")

    faces = "\n".join(
        f"""@font-face {{
  font-family: "Poppins";
  font-style: normal;
  font-weight: {weight};
  font-display: swap;
  src: url("/fonts/{name}") format("woff2");
}}"""
        for weight, name in files.items()
    )
    (WEB / "app" / "fonts.css").write_text(
        "/* Generated by scripts/fonts.py, don't edit */\n\n"
        f"{faces}\n\n"
        "/* Arial resized to Poppins' metrics (the values next/font computes), so\n"
        "   text doesn't move when Poppins swaps in */\n"
        """@font-face {
  font-family: "Poppins Fallback";
  src: local("Arial");
  ascent-override: 93.62%;
  descent-override: 31.21%;
  line-gap-override: 8.92%;
  size-adjust: 112.16%;
}
""",
        newline="\n",
    )
    (WEB / "lib" / "fonts.ts").write_text(
        "// Generated by scripts/fonts.py, don't edit\n\n"
        "/** The self-hosted Poppins files, by weight */\n"
        "export const poppinsFiles = {\n"
        + "".join(f'  {weight}: "/fonts/{name}",\n' for weight, name in files.items())
        + "} as const;\n",
        newline="\n",
    )


if __name__ == "__main__":
    main()
